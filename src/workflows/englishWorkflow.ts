/**
 * Criation UI — Natural Language Workflow Engine
 * 
 * Translates human-readable English rule sentences into structured workflow specifications,
 * reactive state machines, and conventional TypeScript code.
 */

export type TriggerEvent =
  | "QUANTITY_CHANGE"
  | "REMOVE_ITEM"
  | "PROCEED_CHECKOUT"
  | "AUTH_SUCCESS"
  | "LOGOUT"
  | "PAYMENT_SUCCESS"
  | "CUSTOM";

export interface WorkflowCondition {
  field: string;
  operator: "equals" | "greater_than" | "less_than" | "is_zero" | "is_null" | "is_not_null" | "has_items";
  value?: any;
}

export interface WorkflowStep {
  action: string;
  target?: string;
  condition?: WorkflowCondition;
  fallbackAction?: string;
  params?: Record<string, any>;
}

export interface WorkflowRule {
  id: string;
  trigger: TriggerEvent;
  englishTrigger: string;
  description: string;
  steps: WorkflowStep[];
}

export interface WorkflowSpec {
  name: string;
  description?: string;
  rules: WorkflowRule[];
  rawEnglish: string;
}

/**
 * Parses English workflow descriptions into a structured WorkflowSpec AST.
 */
export function parseEnglishWorkflow(englishText: string): WorkflowSpec {
  const text = englishText.trim();
  const rules: WorkflowRule[] = [];

  // Normalize block sections
  const blocks = text
    .split(/(?=When\s+(?:the\s+user|authentication|payment|an?\s+order))/i)
    .map((b) => b.trim())
    .filter(Boolean);

  for (const block of blocks) {
    const lines = block
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean);

    if (lines.length === 0) continue;

    const triggerLine = lines[0].replace(/:$/, "").trim();
    const steps: WorkflowStep[] = [];

    let trigger: TriggerEvent = "CUSTOM";

    // 1. Quantity Change
    if (/changes?\s+(?:a\s+)?product'?s?\s+quantity/i.test(triggerLine)) {
      trigger = "QUANTITY_CHANGE";
      steps.push({
        action: "UPDATE_CART_ITEM",
        target: "cartItem",
      });
      steps.push({
        action: "REMOVE_FROM_CART",
        target: "cartItem",
        condition: { field: "quantity", operator: "is_zero" },
        fallbackAction: "KEEP_CART_ITEM",
      });
    }

    // 2. Remove Item
    else if (/removes?\s+(?:a\s+)?product\s+(?:from\s+(?:the\s+)?cart)?/i.test(triggerLine)) {
      trigger = "REMOVE_ITEM";
      steps.push({
        action: "REMOVE_MATCHING_ITEM",
        target: "cartItem",
      });
    }

    // 3. Proceed to Checkout
    else if (/proceeds?\s+to\s+checkout/i.test(triggerLine)) {
      trigger = "PROCEED_CHECKOUT";
      steps.push({
        action: "CLOSE_CART_DRAWER",
      });
      steps.push({
        action: "OPEN_AUTH_WINDOW",
        condition: { field: "currentUser", operator: "is_null" },
        fallbackAction: "OPEN_CHECKOUT_WINDOW",
      });
    }

    // 4. Authentication Success
    else if (/authentication\s+succeeds?|login\s+succeeds?/i.test(triggerLine)) {
      trigger = "AUTH_SUCCESS";
      steps.push({
        action: "SET_CURRENT_USER",
        target: "user",
      });
      steps.push({
        action: "LOAD_USER_ORDERS",
      });
      steps.push({
        action: "OPEN_CHECKOUT_WINDOW",
        condition: { field: "cartItems", operator: "has_items" },
      });
    }

    // 5. Logout
    else if (/logs?\s+out/i.test(triggerLine)) {
      trigger = "LOGOUT";
      steps.push({
        action: "LOGOUT_AUTH_SERVICE",
      });
      steps.push({
        action: "CLEAR_CURRENT_USER",
      });
      steps.push({
        action: "CLEAR_ORDERS",
      });
      steps.push({
        action: "NAVIGATE_TO",
        params: { route: "store" },
      });
    }

    // 6. Payment Success
    else if (/payment\s+succeeds?|order\s+is\s+placed/i.test(triggerLine)) {
      trigger = "PAYMENT_SUCCESS";
      steps.push({
        action: "CLOSE_CHECKOUT_WINDOW",
      });
      steps.push({
        action: "CLEAR_CART",
      });
      steps.push({
        action: "SHOW_ORDER_RECEIPT",
        condition: { field: "result.order", operator: "is_not_null" },
      });
      steps.push({
        action: "REFRESH_ORDER_HISTORY",
      });
    }

    rules.push({
      id: `rule-${trigger.toLowerCase()}`,
      trigger,
      englishTrigger: triggerLine,
      description: lines.slice(1).join(" "),
      steps,
    });
  }

  return {
    name: "CommerceWorkflow",
    description: "Compiled plain-English reactive state and workflow specification",
    rules,
    rawEnglish: text,
  };
}

/**
 * Compiles plain-English workflow sentences into production-grade, editable TypeScript code.
 */
export function compileEnglishWorkflowToTypeScript(englishText: string): string {
  const spec = parseEnglishWorkflow(englishText);

  return `/**
 * Generated by Criation UI — Natural Language Workflow Compiler
 * Source: ${spec.rules.length} plain-English behavior rules
 */

import { useState, useCallback, useMemo } from "react";
import type { CartItem, Product, User, Order } from "./types";

export function useStoreWorkflow(services: {
  loadOrders: (userId: string) => Promise<Order[]>;
  logout: () => void;
  confirmPayment?: (result: any) => Promise<boolean>;
}) {
  const [cartItems, setCartItems] = useState<CartItem[]>([]);
  const [currentUser, setCurrentUser] = useState<User | null>(null);
  const [orders, setOrders] = useState<Order[]>([]);
  const [currentView, setCurrentView] = useState<"store" | "orders">("store");

  const [isCartOpen, setIsCartOpen] = useState(false);
  const [isAuthOpen, setIsAuthOpen] = useState(false);
  const [isCheckoutOpen, setIsCheckoutOpen] = useState(false);
  const [isReceiptOpen, setIsReceiptOpen] = useState(false);
  const [activeReceiptOrder, setActiveReceiptOrder] = useState<Order | null>(null);

  // 1. "When the user changes a product's quantity"
  const handleUpdateQuantity = useCallback((productId: string, delta: number) => {
    setCartItems((prev) =>
      prev
        .map((item) => {
          if (item.product.id === productId) {
            const nextQ = item.quantity + delta;
            return nextQ > 0 ? { ...item, quantity: nextQ } : null;
          }
          return item;
        })
        .filter(Boolean) as CartItem[]
    );
  }, []);

  // 2. "When the user removes a product from the cart"
  const handleRemoveFromCart = useCallback((productId: string) => {
    setCartItems((prev) => prev.filter((item) => item.product.id !== productId));
  }, []);

  // 3. "When the user proceeds to checkout"
  const handleProceedToCheckout = useCallback(() => {
    setIsCartOpen(false);
    if (!currentUser) {
      setIsAuthOpen(true);
    } else {
      setIsCheckoutOpen(true);
    }
  }, [currentUser]);

  // 4. "When authentication succeeds"
  const handleAuthSuccess = useCallback(async (user: User) => {
    setCurrentUser(user);
    setIsAuthOpen(false);
    const userOrders = await services.loadOrders(user.id);
    setOrders(userOrders);
    setCartItems((currentCart) => {
      if (currentCart.length > 0) {
        setIsCheckoutOpen(true);
      }
      return currentCart;
    });
  }, [services]);

  // 5. "When the user logs out"
  const handleLogout = useCallback(() => {
    services.logout();
    setCurrentUser(null);
    setOrders([]);
    setCurrentView("store");
  }, [services]);

  // 6. "When payment succeeds"
  const handlePaymentSuccess = useCallback(async (result: any) => {
    if (services.confirmPayment) {
      await services.confirmPayment(result);
    }
    setIsCheckoutOpen(false);
    setCartItems([]);
    if (result.order) {
      setActiveReceiptOrder(result.order);
      setIsReceiptOpen(true);
      if (currentUser) {
        const refreshed = await services.loadOrders(currentUser.id);
        setOrders(refreshed);
      }
    }
  }, [services, currentUser]);

  return {
    cartItems,
    currentUser,
    orders,
    currentView,
    isCartOpen,
    setIsCartOpen,
    isAuthOpen,
    setIsAuthOpen,
    isCheckoutOpen,
    setIsCheckoutOpen,
    isReceiptOpen,
    setIsReceiptOpen,
    activeReceiptOrder,
    handleUpdateQuantity,
    handleRemoveFromCart,
    handleProceedToCheckout,
    handleAuthSuccess,
    handleLogout,
    handlePaymentSuccess,
    setCurrentView,
  };
}
`;
}
