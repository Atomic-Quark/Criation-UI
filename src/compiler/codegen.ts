import type { ApplicationModel, ResourceDefinition, FieldDefinition } from "../engine/model";

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface CodegenResult {
  files: GeneratedFile[];
  summary: {
    resourceCount: number;
    pageCount: number;
    fileCount: number;
  };
}

function fieldToTsType(field: FieldDefinition): string {
  switch (field.type) {
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "select":
      if (field.options && field.options.length > 0) {
        return field.options
          .map((opt) => (typeof opt === "string" ? `"${opt}"` : `"${opt.value}"`))
          .join(" | ");
      }
      return "string";
    case "string":
    case "email":
    case "date":
    case "textarea":
    default:
      return "string";
  }
}

/**
 * Generates TypeScript type declarations for all resources in the ApplicationModel.
 */
export function generateResourceTypes(model: ApplicationModel): string {
  let code = `/**
 * Generated Resource Type Definitions
 * Auto-generated by Criation UI Compiler
 */\n\n`;

  for (const [resKey, resource] of Object.entries(model.resources)) {
    code += `export interface ${resource.name} {\n`;
    code += `  id: string | number;\n`;
    for (const field of resource.fields) {
      const isOptional = !field.validation?.required ? "?" : "";
      code += `  ${field.name}${isOptional}: ${fieldToTsType(field)};\n`;
    }
    code += `  createdAt?: string;\n`;
    code += `  updatedAt?: string;\n`;
    code += `}\n\n`;
  }

  return code;
}

/**
 * Generates a clean, editable React Page component for a page in the ApplicationModel.
 */
export function generatePageComponent(pageName: string, model: ApplicationModel): string {
  const page = model.pages.find((p) => p.name === pageName) || model.pages[0];
  const primaryResourceKey = page?.views[0]?.resourceName || Object.keys(model.resources)[0];
  const resource = model.resources[primaryResourceKey];

  if (!resource) {
    throw new Error(`Page '${pageName}' has no valid resource.`);
  }

  const fieldsJson = JSON.stringify(resource.fields, null, 2);

  return `import React from "react";
import { ResourcePage, defineResource } from "@criation/ui";
import type { ${resource.name} } from "../types/resources";

// Resource configuration generated from Application Model
export const ${resource.name}Resource = defineResource({
  name: "${resource.name}",
  singular: "${resource.singular}",
  plural: "${resource.plural}",
  endpoint: "${resource.endpoint}",
  fields: ${fieldsJson}
});

// Seed data for standalone demonstration
const initial${resource.plural}: ${resource.name}[] = [
  { id: "1", name: "Alex Morgan", email: "alex.morgan@example.com", role: "Admin" },
  { id: "2", name: "Jordan Smith", email: "jordan.smith@example.com", role: "Member" },
  { id: "3", name: "Taylor Reed", email: "taylor.reed@example.com", role: "Member" }
];

export function ${page.name}Page() {
  return (
    <ResourcePage
      resource={${resource.name}Resource}
      initialItems={initial${resource.plural}}
      title="${page.title || resource.plural}"
      subtitle="Search, add, edit, and manage all ${resource.plural.toLowerCase()} with live state synchronization."
      apiOptions={{ mockFallback: true }}
    />
  );
}

export default ${page.name}Page;
`;
}

