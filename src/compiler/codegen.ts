/**
 * Generates package.json for the standalone generated application.
 */
export function generatePackageJson(model: ApplicationModel): string {
  return JSON.stringify(
    {
      name: model.name.toLowerCase().replace(/[^a-z0-9-_]/g, "-"),
      version: "0.1.0",
      private: true,
      type: "module",
      scripts: {
        dev: "vite",
        build: "tsc && vite build",
        preview: "vite preview",
      },
      dependencies: {
        "@criation/ui": "file:../UI_Librabry",
        "lucide-react": "^1.16.0",
        react: "^18.3.1",
        "react-dom": "^18.3.1",
      },
      devDependencies: {
        "@types/react": "^18.3.18",
        "@types/react-dom": "^18.3.5",
        "@vitejs/plugin-react": "^4.3.4",
        typescript: "^5.7.2",
        vite: "^6.0.0",
      },
    },
    null,
    2
  );
}

/**
 * Generates index.html for the standalone generated application.
 */
export function generateIndexHtml(model: ApplicationModel): string {
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${model.title || model.name}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>`;
}

/**
 * Generates main.tsx for the standalone generated application.
 */
export function generateMainTsx(): string {
  return `import React from "react";
import ReactDOM from "react-dom/client";
import App from "./App";
import "@criation/ui/styles.css";

ReactDOM.createRoot(document.getElementById("root")!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`;
}

/**
 * Generates vite.config.ts for the standalone generated application.
 */
export function generateViteConfig(): string {
  return `import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  plugins: [react()],
});
`;
}

/**
 * Generates tsconfig.json for the standalone generated application.
 */
export function generateTsConfig(): string {
  return JSON.stringify(
    {
      compilerOptions: {
        target: "ES2020",
        useDefineForClassFields: true,
        lib: ["ES2020", "DOM", "DOM.Iterable"],
        module: "ESNext",
        skipLibCheck: true,
        moduleResolution: "bundler",
        allowImportingTsExtensions: false,
        resolveJsonModule: true,
        isolatedModules: true,
        noEmit: true,
        jsx: "react-jsx",
        strict: true,
        noUnusedLocals: false,
        noUnusedParameters: false,
        noFallthroughCasesInSwitch: true,
      },
      include: ["src"],
    },
    null,
    2
  );
}

/**
 * Main code generation pipeline:
 * Takes an ApplicationModel and produces complete project files.
 */
export function generateReactApplication(model: ApplicationModel): CodegenResult {
  const files: GeneratedFile[] = [];

  // 1. Types
  files.push({
    path: "src/types/resources.ts",
    content: generateResourceTypes(model),
  });

  // 2. Pages
  for (const page of model.pages) {
    const pageFileName = `${page.name}Page.tsx`;
    files.push({
      path: `src/pages/${pageFileName}`,
      content: generatePageComponent(page.name, model),
    });
  }

  // 3. App shell
  files.push({
    path: "src/App.tsx",
    content: generateAppShell(model),
  });

  // 4. Entrypoint
  files.push({
    path: "src/main.tsx",
    content: generateMainTsx(),
  });

  // 5. Config files
  files.push({
    path: "package.json",
    content: generatePackageJson(model),
  });

  files.push({
    path: "index.html",
    content: generateIndexHtml(model),
  });

  files.push({
    path: "vite.config.ts",
    content: generateViteConfig(),
  });

  files.push({
    path: "tsconfig.json",
    content: generateTsConfig(),
  });

  return {
    files,
    summary: {
      resourceCount: Object.keys(model.resources).length,
      pageCount: model.pages.length,
      fileCount: files.length,
    },
  };
}
